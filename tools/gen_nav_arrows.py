#!/usr/bin/env python3
"""Generates the navigation card's turn arrows, drawn like ic_nav_turn_left: 24 x 24, white
2.5 strokes with round ends, tinted in code (the card's green, or grey on the always-on display).
Each right-hand arrow is its left-hand one mirrored. A second, fainter stroke shows the road not
taken (keep left/right, merge). Run from the repository root; the output is committed.
"""
import os

OUT = "app/src/main/res/drawable"

# name: (main strokes, faint strokes)
LEFT = {
    "straight": (["M12,21V4", "M6,10l6,-6 6,6"], []),
    "turn_left": (["M20,20v-7a4,4 0 0 0-4,-4H4", "M9,14L4,9l5,-5"], []),
    "slight_left": (["M16,21v-6a3,3 0 0 0-0.9,-2.1L7,5", "M7,11V5h6"], []),
    "sharp_left": (["M17,21V9a3,3 0 0 0-5.1,-2.1L5.5,13.5", "M5,8v6h6"], []),
    "uturn_left": (["M17,21V9a5,5 0 0 0-10,0v9", "M3,14l4,4 4,-4"], []),
    "keep_left": (["M12,21v-6", "M12,15L7,10V4", "M4,7l3,-3 3,3"], ["M12,15l5,-5V5"]),
    "merge_left": (["M7,21v-5l5,-5V4", "M8,8l4,-4 4,4"], ["M17,21v-5l-3,-3"]),
    "roundabout": (["M12,21v-7", "M14.8,7.2L19,3", "M14,3h5v5", "M12,14a4,4 0 1 1 2.8,-6.8"], []),
}


def path(d, faint):
    alpha = '\n        android:strokeAlpha="0.4"' if faint else ''
    return f'''    <path android:pathData="{d}"
        android:fillColor="#00000000"
        android:strokeColor="#FFFFFFFF"{alpha}
        android:strokeWidth="2.5"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />'''


def vector(name, main, faint, mirror):
    body = "\n".join([path(d, True) for d in faint] + [path(d, False) for d in main])
    if mirror:
        body = '    <group android:scaleX="-1" android:pivotX="12">\n' + body.replace("\n    ", "\n        ").replace("    <path", "        <path", 1) + "\n    </group>"
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Navigation arrow "{name}". Generated by tools/gen_nav_arrows.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{body}
</vector>
'''


count = 0
for name, (main, faint) in LEFT.items():
    with open(os.path.join(OUT, f"ic_nav_dir_{name}.xml"), "w") as f:
        f.write(vector(name, main, faint, False))
    count += 1
    if name.endswith("_left"):
        right = name[: -len("_left")] + "_right"
        with open(os.path.join(OUT, f"ic_nav_dir_{right}.xml"), "w") as f:
            f.write(vector(right, main, faint, True))
        count += 1
print("ok", count, "arrows")
