#!/usr/bin/env python3
"""Generates the hold-to-dismiss ring (spec 6.3, drawn round the whole card).

The ring is an <animated-selector>: Android plays its transition while the card is pressed,
with no app code involved, so it works inside RemoteViews. A line traces the card's rounded
edge clockwise from the top centre. One set per colour (red on dismissible cards, amber on the
pinned weather card) and per touch-and-hold delay setting (short, medium, long).

Timing: Pixel Launcher opens its long-press menu at 3/4 of the touch-and-hold delay (Launcher3's
long-press factor), and a view in a scrolling container only shows as pressed 100 ms after the
touch, which also keeps quick taps from flashing the ring. The ring closes at 90% of the time
between the two, so it is complete just before the menu appears.

The path is drawn for a 420 x 104 dp card (the card's width as laid out before the launcher
scales it, and its default height) with 24 dp corners; on a card of another size (the Card height
setting) the corners stretch slightly. Run from the repository root; the output is committed.
"""
import os

RES = "app/src/main/res/drawable"
COLOURS = {"red": "#FFF43F5E", "amber": "#FFF59E0B"}
TAP_TIMEOUT = 100
LAUNCHER_FACTOR = 0.75
FINISH_EARLY = 0.9
TIMEOUTS = (400, 1000, 1500)
W, H, R, STROKE = 420, 104, 24, 2.5
i = STROKE / 2
r = R - i
PATH = (f"M{W/2},{i} H{W-R} A{r},{r} 0 0 1 {W-i},{R} V{H-R} A{r},{r} 0 0 1 {W-R},{H-i} "
        f"H{R} A{r},{r} 0 0 1 {i},{H-R} V{R} A{r},{r} 0 0 1 {R},{i} Z")


def vector(colour, trim_end):
    return f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{W}dp"
    android:height="{H}dp"
    android:viewportWidth="{W}"
    android:viewportHeight="{H}">
    <path
        android:name="ring"
        android:pathData="{PATH}"
        android:strokeColor="{colour}"
        android:strokeLineCap="round"
        android:strokeWidth="{STROKE}"
        android:trimPathEnd="{trim_end}" />
</vector>'''


def write(name, body, comment):
    with open(os.path.join(RES, name + ".xml"), "w") as f:
        f.write(f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} -->\n{body}\n')


write("hold_bar_empty", vector("#00000000", 0), "Hold ring at rest (generated by tools/gen_hold_bars.py)")
for name, colour in COLOURS.items():
    write(f"hold_bar_{name}_full", vector(colour, 1), f"Hold ring, {name}, closed")
    # The animation's starting picture: nothing drawn yet, so the start delay shows no ring.
    write(f"hold_bar_{name}_zero", vector(colour, 0), f"Hold ring, {name}, not started")
    for timeout in TIMEOUTS:
        ms = int((timeout * LAUNCHER_FACTOR - TAP_TIMEOUT) * FINISH_EARLY)
        avd = f"avd_hold_{name}_{timeout}"
        write(avd, f'''<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/hold_bar_{name}_zero">
    <target android:name="ring">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="{ms}"
                android:interpolator="@android:interpolator/linear"
                android:propertyName="trimPathEnd"
                android:valueFrom="0"
                android:valueTo="1"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
</animated-vector>''', f"Hold ring trace, {name}, {ms} ms")
        write(f"hold_bar_{name}_{timeout}", f'''<animated-selector xmlns:android="http://schemas.android.com/apk/res/android">
    <item
        android:id="@+id/hold_pressed"
        android:drawable="@drawable/hold_bar_{name}_full"
        android:state_pressed="true" />
    <item
        android:id="@+id/hold_idle"
        android:drawable="@drawable/hold_bar_empty" />
    <transition
        android:drawable="@drawable/{avd}"
        android:fromId="@id/hold_idle"
        android:toId="@id/hold_pressed" />
</animated-selector>''', f"Hold ring, {name}, for a {timeout} ms touch-and-hold delay")
