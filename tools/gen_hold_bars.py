#!/usr/bin/env python3
"""Generates the hold-to-dismiss bars (spec 6.3).

The bar is an <animated-selector>: Android plays its transition while the card is pressed,
with no app code involved, so it works inside RemoteViews. One set per colour (red on
dismissible cards, amber on the pinned weather card) and per touch-and-hold delay setting
(short, medium, long). Each duration is the delay minus the 100 ms tap timeout, because a view
inside a scrolling container only shows as pressed after that timeout.

Run from the repository root; the output is committed.
"""
import os

RES = "app/src/main/res/drawable"
COLOURS = {"red": "#FFF43F5E", "amber": "#FFF59E0B"}
DURATIONS = {400: 300, 1000: 900, 1500: 1400}
PATH = "M1.5,1.5 L98.5,1.5"


def vector(colour, trim_end):
    return f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="100dp"
    android:height="3dp"
    android:viewportWidth="100"
    android:viewportHeight="3">
    <path
        android:name="bar"
        android:pathData="{PATH}"
        android:strokeColor="{colour}"
        android:strokeLineCap="round"
        android:strokeWidth="3"
        android:trimPathEnd="{trim_end}" />
</vector>'''


def write(name, body, comment):
    with open(os.path.join(RES, name + ".xml"), "w") as f:
        f.write(f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} -->\n{body}\n')


write("hold_bar_empty", vector("#00000000", 0), "Hold bar at rest (generated by tools/gen_hold_bars.py)")
for name, colour in COLOURS.items():
    write(f"hold_bar_{name}_full", vector(colour, 1), f"Hold bar, {name}, filled")
    for timeout, ms in DURATIONS.items():
        avd = f"avd_hold_{name}_{timeout}"
        write(avd, f'''<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/hold_bar_{name}_full">
    <target android:name="bar">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="{ms}"
                android:interpolator="@android:interpolator/linear"
                android:propertyName="trimPathEnd"
                android:valueFrom="0"
                android:valueTo="1"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
</animated-vector>''', f"Hold bar fill, {name}, {ms} ms")
        write(f"hold_bar_{name}_{timeout}", f'''<animated-selector xmlns:android="http://schemas.android.com/apk/res/android">
    <item
        android:id="@+id/hold_pressed"
        android:drawable="@drawable/hold_bar_{name}_full"
        android:state_pressed="true" />
    <item
        android:id="@+id/hold_idle"
        android:drawable="@drawable/hold_bar_empty" />
    <transition
        android:drawable="@drawable/{avd}"
        android:fromId="@id/hold_idle"
        android:toId="@id/hold_pressed" />
</animated-selector>''', f"Hold bar, {name}, for a {timeout} ms touch-and-hold delay")
