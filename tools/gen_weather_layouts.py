# The tiles' text sizes are set in code (in dp, one size per card, so neighbours match and the
# fixed lines always hold them); the sizes here are only defaults.
def text(id_, colour, medium=False, width="wrap_content", extra="", gone=False):
    fam = "sans-serif-medium" if medium else "sans-serif"
    vis = chr(10) + '        android:visibility="gone"' if gone else ""
    return f"""<TextView
        android:id="@+id/{id_}"
        android:layout_width="{width}"
        android:layout_height="wrap_content"
        android:ellipsize="end"
        android:fontFamily="{fam}"
        android:includeFontPadding="false"
        android:singleLine="true"
        android:textColor="{colour}"
        android:textSize="11sp"{extra}{vis} />"""


def indent(block, n):
    return "\n".join((" " * n + line) if line else line for line in block.split("\n"))


