#!/usr/bin/env python3
"""Generates the sports and Formula 1 cards' drawables (Material You sports spec, section 3).

The team cards take each team's own colours in code: a neutral arena surface with a soft wash of
the home team's colour from the left and the away team's from the right (white washes, tinted),
team circles (white, tinted) and their rims. The HOME / AWAY tags, the status pills and the F1
card's parts use the spec's colours as given.

Run from the repository root:  python3 tools/gen_sports_drawables.py
"""
import os

OUT = "app/src/main/res/drawable"
HDR = '<?xml version="1.0" encoding="utf-8"?>\n'
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'


def write(name, comment, body):
    with open(os.path.join(OUT, name + ".xml"), "w") as f:
        f.write(HDR + f"<!-- {comment} Generated by tools/gen_sports_drawables.py. -->\n" + body)


def shape(name, comment, fill=None, stroke=None, stroke_w="1dp", radius=None, oval=False, gradient=None):
    parts = []
    if gradient:
        start, center, end, angle = gradient
        parts.append(f'<gradient android:angle="{angle}" android:startColor="{start}" android:centerColor="{center}" android:endColor="{end}" android:type="linear" />')
    elif fill:
        parts.append(f'<solid android:color="{fill}" />')
    if stroke:
        parts.append(f'<stroke android:width="{stroke_w}" android:color="{stroke}" />')
    if radius and not oval:
        parts.append(f'<corners android:radius="{radius}" />')
    kind = "oval" if oval else "rectangle"
    write(name, comment, f'<shape {A} android:shape="{kind}">\n    ' + "\n    ".join(parts) + "\n</shape>\n")


# --- Team cards (sports spec 3.1, 3.2) ---

shape("sports_surface", "Team card surface: the neutral arena slate in the middle of the spec's split (team washes go over it).",
      fill="#F2161C28", radius="24dp")
shape("sports_border", "Team card edge.", fill="#00000000", stroke="#29FFFFFF", radius="24dp")


def wash(name, left):
    # White fading to clear across the card's half; the card tints it with the team's colour.
    x1, x2 = (0, 230) if left else (420, 190)
    write(name, f"Team colour wash from the {'left (home)' if left else 'right (away)'}: white, tinted in code.", f'''<vector {A} {AAPT}
    android:width="420dp"
    android:height="76dp"
    android:viewportWidth="420"
    android:viewportHeight="76">
    <path android:pathData="M0,0 H420 V76 H0 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x1}" android:startY="0" android:endX="{x2}" android:endY="0"
                android:startColor="#38FFFFFF" android:endColor="#00FFFFFF" />
        </aapt:attr>
    </path>
</vector>
''')


wash("sports_wash_home", True)
wash("sports_wash_away", False)

write("sports_wave", "The live card's organic tonal wave in the bottom right (sports spec 3.1).", f'''<vector {A}
    android:width="96dp"
    android:height="64dp"
    android:viewportWidth="96"
    android:viewportHeight="64">
    <path android:fillColor="#1F64B5F6" android:pathData="M0,64 C16,62 22,48 38,42 C56,35 70,38 82,26 C90,18 93,9 96,0 L96,64 Z" />
</vector>
''')

shape("team_circle", "A team's logo circle: white, tinted with the team's colour in code.", fill="#FFFFFFFF", oval=True)
shape("team_ring", "A team circle's 1.5dp rim: white, tinted in code.", fill="#00000000", stroke="#FFFFFFFF", stroke_w="1.5dp", oval=True)

shape("tag_home_live", "HOME tag on a live or finished game (sports spec 3.1).", fill="#FFFFB4AB", radius="6.5dp")
shape("tag_away_live", "AWAY tag on a live or finished game (sports spec 3.1).", fill="#FFC4C6D0", radius="6.5dp")
shape("tag_home_next", "HOME tag on an upcoming game (sports spec 3.2).", fill="#FFB8C4FF", radius="6.5dp")
shape("tag_away_next", "AWAY tag on an upcoming game (sports spec 3.2).", fill="#FFF2B8B5", radius="6.5dp")

shape("status_pill_live", "LIVE pill (sports spec 3.1).", fill="#FF4A1C20", stroke="#80FF5252", radius="9dp")
shape("status_pill_next", "Upcoming game pill: 'Next game' or the countdown (sports spec 3.2).", fill="#FF1E2F42", stroke="#4D7FCFFF", radius="9.5dp")
shape("status_pill_final", "Finished game pill, in the spec's neutral tones.", fill="#FF262C38", stroke="#33FFFFFF", radius="9dp")
shape("live_dot", "LIVE pill's dot.", fill="#FFFF6B6B", oval=True)

# --- Formula 1 (sports spec 3.3) ---

shape("f1_surface", "F1 card surface and edge: racing green to carbon slate, 135 degrees (sports spec 3.3).",
      gradient=("#F20F2622", "#F20D1F1D", "#F20A1618", 315), stroke="#334DB6AC", radius="24dp")
shape("f1_track_box", "F1 circuit box.", fill="#FF123832", stroke="#4D4EE2C0", radius="14dp")
shape("f1_countdown_pill", "F1 countdown pill.", fill="#FF3B2328", stroke="#4DFF8A80", radius="8dp")
shape("f1_live_pill", "F1 live pill.", fill="#FF4A1C20", stroke="#80FF5252", radius="8dp")
shape("f1_mini_badge", "F1 box's small corner mark.", fill="#FF38E5B5", radius="2.5dp")
write("f1_next_btn", "F1 Next button: emerald, lighter while pressed (sports spec 3.3).", f'''<selector {A}>
    <item android:state_pressed="true">
        <shape android:shape="rectangle">
            <solid android:color="#FF1D6E5E" />
            <stroke android:width="1dp" android:color="#6638E5B5" />
            <corners android:radius="18dp" />
        </shape>
    </item>
    <item>
        <shape android:shape="rectangle">
            <solid android:color="#FF134E42" />
            <stroke android:width="1dp" android:color="#6638E5B5" />
            <corners android:radius="18dp" />
        </shape>
    </item>
</selector>
''')
print("ok")
