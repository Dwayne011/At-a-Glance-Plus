#!/usr/bin/env python3
"""Generates the F1 card's circuit icons from the f1-circuits project's track outlines.

Source: https://github.com/bacinger/f1-circuits (MIT licence, (c) Tomislav Bacinger), the file
f1-circuits.geojson. Each outline is projected flat, simplified, and scaled into a 24 x 24 icon
drawn as a line (white for the card, grey for the always-on display). Also writes CircuitIcons.kt,
which matches a race's circuit to its icon by city or circuit name.

Run from the repository root:  python3 tools/gen_circuits.py path/to/f1-circuits.geojson
"""
import json
import math
import os
import sys
import unicodedata

DRAWABLES = "app/src/main/res/drawable"
KOTLIN = "app/src/main/java/com/ataglanceplus/cards/CircuitIcons.kt"
HDR = '<?xml version="1.0" encoding="utf-8"?>\n'


def normal(text):
    """Lower case, no accents or punctuation: "São Paulo" -> "sao paulo"."""
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return " ".join("".join(c if c.isalnum() else " " for c in text.lower()).split())


def simplify(points, tolerance):
    """Ramer-Douglas-Peucker."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy) or 1e-9
    worst, index = 0.0, 0
    for i in range(1, len(points) - 1):
        x, y = points[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / length
        if d > worst:
            worst, index = d, i
    if worst <= tolerance:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tolerance)[:-1] + simplify(points[index:], tolerance)


def icon_path(coords):
    lat0 = sum(c[1] for c in coords) / len(coords)
    flat = [(lon * math.cos(math.radians(lat0)), -lat) for lon, lat in coords]
    xs, ys = [p[0] for p in flat], [p[1] for p in flat]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    scale = 20 / max(w, h)
    ox, oy = (24 - w * scale) / 2, (24 - h * scale) / 2
    pts = [((x - min(xs)) * scale + ox, (y - min(ys)) * scale + oy) for x, y in flat]
    # A loop starts and ends at the same point, so simplify its two halves, split at the point
    # farthest from the start.
    far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
    pts = simplify(pts[: far + 1], 0.12)[:-1] + simplify(pts[far:], 0.12)
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"


def vector(path, colour, name):
    return HDR + f'''<!-- Circuit outline: {name}. From the f1-circuits project (MIT). Generated by tools/gen_circuits.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#00000000"
        android:pathData="{path}"
        android:strokeColor="{colour}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:strokeWidth="1.5" />
</vector>
'''


def main(source):
    features = json.load(open(source))["features"]
    entries = []
    for f in features:
        props = f["properties"]
        cid = props["id"].replace("-", "_")
        geometry = f["geometry"]
        coords = geometry["coordinates"]
        if geometry["type"] == "MultiLineString":
            coords = max(coords, key=len)
        path = icon_path(coords)
        for suffix, colour in (("", "#FFFFFFFF"), ("_aod", "#FF9AA0A6")):
            with open(os.path.join(DRAWABLES, f"ic_circuit_{cid}{suffix}.xml"), "w") as out:
                out.write(vector(path, colour, props["Name"]))
        entries.append((cid, normal(props["Location"]), normal(props["Name"])))

    rows = ",\n".join(
        f'        Circuit("{city}", "{name}", R.drawable.ic_circuit_{cid}, R.drawable.ic_circuit_{cid}_aod)'
        for cid, city, name in sorted(entries)
    )
    with open(KOTLIN, "w") as out:
        out.write(f'''package com.ataglanceplus.cards

import androidx.annotation.DrawableRes
import com.ataglanceplus.R
import java.text.Normalizer

/**
 * Track outlines for the F1 card, matched to a race by its city or circuit name. Generated by
 * tools/gen_circuits.py from the f1-circuits project (MIT licence, (c) Tomislav Bacinger).
 */
object CircuitIcons {{

    private class Circuit(val city: String, val name: String, @DrawableRes val icon: Int, @DrawableRes val aodIcon: Int)

    private val CIRCUITS = listOf(
{rows},
    )

    /** The outline for a circuit in [city] or named [name] (as ESPN gives them), or null. */
    fun find(city: String?, name: String?, aod: Boolean): Int? {{
        val c = city?.let(::normal).orEmpty()
        val n = name?.let(::normal).orEmpty()
        val match = CIRCUITS.firstOrNull {{ c.isNotEmpty() && it.city == c }}
            ?: CIRCUITS.firstOrNull {{ n.isNotEmpty() && (it.name == n || it.name.contains(n) || n.contains(it.name)) }}
            // Names differ in wording ("Autodromo Hermanos Rodriguez" for "Autódromo Hermanos
            // Rodríguez"): at least two distinctive words in common.
            ?: CIRCUITS.firstOrNull {{ circuit -> n.isNotEmpty() && words(circuit.name).intersect(words(n)).size >= 2 }}
        return match?.let {{ if (aod) it.aodIcon else it.icon }}
    }}

    private val COMMON = setOf("circuit", "international", "autodromo", "grand", "prix", "street", "de", "del", "the", "of", "racing", "course")

    private fun words(text: String) = text.split(" ").filter {{ it.length > 2 && it !in COMMON }}.toSet()

    private fun normal(text: String): String =
        Normalizer.normalize(text, Normalizer.Form.NFKD).replace(Regex("\\\\p{{M}}+"), "").lowercase()
            .map {{ if (it.isLetterOrDigit()) it else ' ' }}.joinToString("").split(" ").filter {{ it.isNotEmpty() }}.joinToString(" ")
}}
''')
    print("ok", len(entries), "circuits")


main(sys.argv[1])
