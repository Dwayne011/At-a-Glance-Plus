#!/usr/bin/env python3
"""Generates the chips' tonal backgrounds (Material You chips spec, section 2.2 and 2.3).

Each palette gets a pill (13dp corners, for one slot or two across) and a rounded card (14dp
corners, for two slots stacked), each a selector: the tonal fill with its 1dp stroke, and when
pressed, a 20% white layer over the fill with the stroke raised to 60% white. Also writes the 2dp
progress line used by the steps chip (white on a 30% white track).

Run from the repository root:  python3 tools/gen_chip_tones.py
"""
import os

OUT = "app/src/main/res/drawable"
HDR = '<?xml version="1.0" encoding="utf-8"?>\n'

# name: (fill, stroke). Dark variants for missed calls and texts.
TONES = {
    "gmail": ("#FF2D4B75", "#FF5B82B8"),
    "calls": ("#FF602D30", "#FFFC0204"),
    "texts": ("#FF284848", "#FF4FD8EB"),
    "notif": ("#FF3C2D5C", "#FF7E67B5"),
    "steps": ("#FF25443B", "#FF4C7C6D"),
    "sleep": ("#FF283556", "#FF536799"),
    "health": ("#FF4E2835", "#FF8C4F63"),
    "battery": ("#FF2A4730", "#FF52825B"),
    "buds": ("#FF234346", "#FF497D82"),
    "screen": ("#FF323A4E", "#FF5C6887"),
    "alarm": ("#FF4D3E24", "#FF8F7445"),
    "count": ("#FF364251", "#FF63768E"),
    "sunset": ("#FF4A3728", "#FF87654B"),
    "etoro": ("#FF24422B", "#FF497D55"),
    # Not in the spec: the eToro chip when the portfolio is down, in the health chip's red tones.
    "etoro_loss": ("#FF4A2626", "#FF8C4F4F"),
    "ticket": ("#FF3A305D", "#FF6E5DA8"),
}


def shape(fill, stroke, radius):
    return f'''<shape android:shape="rectangle">
            <solid android:color="{fill}" />
            <stroke android:width="1dp" android:color="{stroke}" />
            <corners android:radius="{radius}dp" />
        </shape>'''


def selector(name, fill, stroke, radius, what):
    return HDR + f'''<!-- Chip tone "{name}" ({what}): tonal fill and stroke; pressed adds a 20% white layer and a 60% white rim. Generated by tools/gen_chip_tones.py. -->
<selector xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:state_pressed="true">
        <layer-list>
            <item>
                {shape(fill, "#99FFFFFF", radius)}
            </item>
            <item>
                <shape android:shape="rectangle">
                    <solid android:color="#33FFFFFF" />
                    <corners android:radius="{radius}dp" />
                </shape>
            </item>
        </layer-list>
    </item>
    <item>
        {shape(fill, stroke, radius)}
    </item>
</selector>
'''


for name, (fill, stroke) in TONES.items():
    with open(os.path.join(OUT, f"chip_tone_{name}.xml"), "w") as f:
        f.write(selector(name, fill, stroke, 13, "pill"))
    with open(os.path.join(OUT, f"chip_tone_{name}_stack.xml"), "w") as f:
        f.write(selector(name, fill, stroke, 14, "stacked card"))

with open(os.path.join(OUT, "chip_progress.xml"), "w") as f:
    f.write(HDR + '''<!-- A chip's 2dp progress line (steps toward the goal): white on a 30% white track. Generated by tools/gen_chip_tones.py. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:id="@android:id/background">
        <shape android:shape="rectangle">
            <solid android:color="#4DFFFFFF" />
            <corners android:radius="1dp" />
        </shape>
    </item>
    <item android:id="@android:id/progress">
        <clip android:clipOrientation="horizontal" android:gravity="start">
            <shape android:shape="rectangle">
                <solid android:color="#FFFFFFFF" />
                <corners android:radius="1dp" />
            </shape>
        </clip>
    </item>
</layer-list>
''')
print("ok", len(TONES), "tones")
