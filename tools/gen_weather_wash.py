#!/usr/bin/env python3
"""Generates the Weather wash look's drawables: the card's gradient for each kind of weather by
day and night (top colour first), and the frosted glass panels and tiles over it, lighter
glass on the light washes and fainter glass on the dark ones.

Run from the repository root:  python3 tools/gen_weather_wash.py
"""
import os

OUT = "app/src/main/res/drawable"
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'

# (top, bottom) for day and night.
WASH = {
    "clear":   (("#FFFF9E5E", "#FFFFD36E"), ("#FF1A1D45", "#FF463C80")),
    "partly":  (("#FF7FB2E5", "#FFF7D9A8"), ("#FF22285A", "#FF4A4A86")),
    "cloudy":  (("#FF93A7BA", "#FFCBD6DF"), ("#FF2C3442", "#FF56627A")),
    "fog":     (("#FFA9B4BE", "#FFD9DEE2"), ("#FF343A44", "#FF5A626E")),
    "rain":    (("#FF41607E", "#FF7890A8"), ("#FF1E2A3C", "#FF3E536C")),
    "snow":    (("#FF9DB6D3", "#FFE6EEF7"), ("#FF26324A", "#FF55688A")),
    "thunder": (("#FF3A3F5A", "#FF6B6A8A"), ("#FF191B2E", "#FF3B3756")),
}


def write(name, body, comment):
    with open(os.path.join(OUT, name + ".xml"), "w") as f:
        f.write(f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by tools/gen_weather_wash.py. -->\n{body}\n')


for kind, times in WASH.items():
    for time, (top, bottom) in zip(("day", "night"), times):
        write(f"weather_wash_{kind}_{time}",
              f'<shape {A} android:shape="rectangle">\n    <gradient android:angle="270" android:startColor="{top}" android:endColor="{bottom}" android:type="linear" />\n</shape>',
              f"Weather wash: {kind}, {time}.")

write("weather_wash_frame",
      f'<shape {A} android:shape="rectangle">\n    <solid android:color="#00000000" />\n    <stroke android:width="1dp" android:color="#33FFFFFF" />\n    <corners android:radius="26dp" />\n</shape>',
      "Weather wash: the card's faint edge; the wash shows through.")
for shade, panel, tile in (("light", "#66FFFFFF", "#A6FFFFFF"), ("dark", "#3DFFFFFF", "#4DFFFFFF")):
    write(f"weather_wash_panel_{shade}",
          f'<shape {A} android:shape="rectangle">\n    <solid android:color="{panel}" />\n    <corners android:radius="20dp" />\n</shape>',
          f"Weather wash: a frosted panel on a {shade} wash.")
    write(f"weather_wash_tile_{shade}",
          f'<shape {A} android:shape="rectangle">\n    <solid android:color="{tile}" />\n    <corners android:radius="12dp" />\n</shape>',
          f"Weather wash: a chip tile on a {shade} wash.")
